local JOINT_POSES = {
	["Torso"] = "RootJoint",
	["Head"] = "Neck",
	["Left Arm"] = "Left Shoulder",
	["Right Arm"] = "Right Shoulder",
	["Left Leg"] = "Left Hip",
	["Right Leg"] = "Right Hip",
}

local function toCFrame(values)
	return CFrame.new(table.unpack(values))
end

local function findMotors(character)
	local motors = {}
	for _, descendant in ipairs(character:GetDescendants()) do
		if descendant:IsA("Motor6D") then
			motors[descendant.Name] = descendant
		end
	end
	local required = {"RootJoint", "Neck", "Left Shoulder", "Right Shoulder", "Left Hip", "Right Hip"}
	for _, name in ipairs(required) do
		if not motors[name] then
			return nil, "R6 Motor6D missing: " .. name
		end
	end
	return motors
end

local function samplePose(timePosition, poseName)
	local previous, following
	for _, frame in ipairs(FRAMES) do
		local values = frame[2][poseName]
		if values then
			if frame[1] <= timePosition then
				previous = {time = frame[1], cf = toCFrame(values)}
			elseif not following then
				following = {time = frame[1], cf = toCFrame(values)}
				break
			end
		end
	end
	if not previous and following then return following.cf end
	if previous and not following then return previous.cf end
	if not previous and not following then return CFrame.identity end
	local span = following.time - previous.time
	if span <= 0 then return following.cf end
	return previous.cf:Lerp(following.cf, math.clamp((timePosition - previous.time) / span, 0, 1))
end

-- Play(character, options) returns a Stop() handle.
-- options.Looped = true/false; options.Speed = positive number.
function HakariMoves.Play(character, options)
	options = options or {}
	if not character or not character:IsA("Model") then
		return nil, "Character Model required"
	end
	local humanoid = character:FindFirstChildOfClass("Humanoid")
	if not humanoid or humanoid.RigType ~= Enum.HumanoidRigType.R6 then
		return nil, "HakariMoves requires an R6 character"
	end
	local motors, err = findMotors(character)
	if not motors then return nil, err end

	local speed = tonumber(options.Speed) or 1
	if speed <= 0 then speed = 1 end
	local looped = options.Looped == true
	local baseC0, poseToMotor = {}, {}
	for poseName, motorName in pairs(JOINT_POSES) do
		local motor = motors[motorName]
		baseC0[motorName] = motor.C0
		poseToMotor[poseName] = motor
	end

	local stopped = false
	local startTime = os.clock()
	local connection
	local handle = {}
	function handle:Stop()
		if stopped then return end
		stopped = true
		if connection then connection:Disconnect(); connection = nil end
		for motorName, originalC0 in pairs(baseC0) do
			local motor = motors[motorName]
			if motor and motor.Parent then motor.C0 = originalC0 end
		end
	end

	connection = RunService.RenderStepped:Connect(function()
		if stopped or not character.Parent or humanoid.Health <= 0 then
			handle:Stop()
			return
		end
		local t = (os.clock() - startTime) * speed
		if looped then
			t = t % HakariMoves.Duration
		elseif t >= HakariMoves.Duration then
			handle:Stop()
			return
		end
		for poseName, motor in pairs(poseToMotor) do
			motor.C0 = baseC0[motor.Name] * samplePose(t, poseName)
		end
	end)
	return handle
end

HakariMoves.Frames = FRAMES
return HakariMoves
